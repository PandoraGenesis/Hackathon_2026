function translateNode(node, lang) {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node.nodeValue.trim();
    if (text && text !== 'VN' && text !== 'EN' && text !== '|') {
      if (lang === 'en' && dict[text]) {
        node.nodeValue = node.nodeValue.replace(text, dict[text]);
      } else if (lang === 'vn' && reverseDict[text]) {
        node.nodeValue = node.nodeValue.replace(text, reverseDict[text]);
      } else {
        if (lang === 'en') {
          let updated = node.nodeValue;
          for (const [v, e] of Object.entries(dict)) {
            if (v !== 'VN' && v !== 'EN' && updated.includes(v)) updated = updated.replace(v, e);
          }
          if (updated !== node.nodeValue) node.nodeValue = updated;
        } else if (lang === 'vn') {
          let updated = node.nodeValue;
          for (const [v, e] of Object.entries(dict)) {
            if (v !== 'VN' && v !== 'EN' && updated.includes(e)) updated = updated.replace(e, v);
          }
          if (updated !== node.nodeValue) node.nodeValue = updated;
        }
      }
    }
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
    if (node.tagName === 'INPUT' && node.placeholder) {
        const text = node.placeholder.trim();
        if (lang === 'en' && dict[text]) node.placeholder = dict[text];
        else if (lang === 'vn' && reverseDict[text]) node.placeholder = reverseDict[text];
    }
    for (const child of node.childNodes) {
      translateNode(child, lang);
    }
  }
}

function updateLanguage(lang) {
  document.documentElement.lang = lang;
  translateNode(document.body, lang);
  const btns = document.querySelectorAll('.lang-btn');
  btns.forEach(btn => {
    if (btn.textContent.trim().toLowerCase() === lang.toLowerCase()) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const btns = document.querySelectorAll('.lang-btn');
  btns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      const lang = e.target.textContent.trim().toLowerCase();
      if (lang === 'en' || lang === 'vn') {
          updateLanguage(lang);
      }
    });
  });
});
